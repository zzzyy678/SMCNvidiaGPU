#!/usr/bin/env python3
"""Keep the kext usable on driver builds other than the one it was compiled against.

build.sh calls this twice: first to archive the nvrm_bindings.h of the driver that is currently installed
(before regenerating for a new one), then to render every archived table into nvrm_bindings_legacy.h. The
kext tries its own table first and falls back to the archived ones, so a user who stays on an older driver
still gets sensors after we ship a build made for a newer driver.

    kext/bindings_legacy.py --archive <nvrm_bindings.h> <archive-dir> <label>
    kext/bindings_legacy.py --generate <archive-dir> <nvrm_bindings_legacy.h>
"""
import os
import re
import shutil
import sys

ENTRIES = ["gpumgrGetGpu", "createRusd", "linkRusd", "lock", "unlock", "pmEnter", "pmExit"]

HEADER = """/* nvrm_bindings_legacy.h — generated by bindings_legacy.py; do not edit.
 *
 * Binding tables for driver builds other than the one this kext was compiled against, so an installed
 * driver that does not match the current table still binds instead of leaving every sensor at zero.
 */
#pragma once

struct NvrmLegacyBinding {
    const char *label;
    UInt64 anchorOff; const unsigned char *sigAnchor;
    UInt64 gpuOff;    const unsigned char *sigGpu;
    UInt64 createOff; const unsigned char *sigCreate;
    UInt64 linkOff;   const unsigned char *sigLink;
    UInt64 lockOff;   const unsigned char *sigLock;
    UInt64 unlockOff; const unsigned char *sigUnlock;
    UInt64 pmInOff;   const unsigned char *sigPmIn;
    UInt64 pmOutOff;  const unsigned char *sigPmOut;
};

"""


def parse(path):
    text = open(path).read()
    m = re.search(r'#define NVRM_DRIVER_SHA256 "([0-9a-f]{64})"', text) or \
        re.search(r'driver sha256 ([0-9a-f]{64})', text)
    data = {"sha": m.group(1) if m else "unknown"}

    def one(pat, cast=int):
        hit = re.search(pat, text)
        return cast(hit.group(1), 16) if hit else None

    def array(name):
        hit = re.search(r'static const unsigned char %s\[[^\]]*\] = \{([^}]*)\}' % name, text)
        return [b.strip() for b in hit.group(1).split(",") if b.strip()] if hit else None

    data["anchor"] = one(r'#define NVRM_ANCHOR_OFF\s+(0x[0-9a-fA-F]+)ULL')
    data["sig_anchor"] = array("NVRM_SIG_anchor")
    data["entries"] = [(name,
                        one(r'#define NVRM_OFF_%s\s+(0x[0-9a-fA-F]+)ULL' % name),
                        array("NVRM_SIG_" + name)) for name in ENTRIES]
    if data["anchor"] is None or data["sig_anchor"] is None or any(e[1] is None or e[2] is None for e in data["entries"]):
        raise ValueError("not a complete binding header: %s" % path)
    return data


def installed_driver_sha():
    import hashlib
    try:
        with open("/Library/Extensions/NVRM.kext/Contents/MacOS/NVRM", "rb") as f:
            return hashlib.sha256(f.read()).hexdigest()
    except Exception:
        return None


def archive(src, outdir, label):
    data = parse(src)
    current = installed_driver_sha()
    if current and current == data["sha"]:
        return  # same build as the installed driver: it is regenerated anyway, no archive needed
    if current and current != data["sha"]:
        # The header belongs to a driver that is no longer installed: label it by its own build.
        label = "build-" + data["sha"][:8]
    os.makedirs(outdir, exist_ok=True)
    name = "%s-%s.h" % (label, data["sha"][:8])
    dst = os.path.join(outdir, name)
    if not os.path.exists(dst):
        shutil.copyfile(src, dst)
        print("archived bindings for driver %s" % label)
    return dst


def generate(outdir, dst):
    blocks, entries = [], []
    for name in sorted(os.listdir(outdir)):
        if not name.endswith(".h"):
            continue
        label = name.rsplit("-", 1)[0]
        data = parse(os.path.join(outdir, name))
        ident = "kLegacy_" + re.sub(r'[^0-9A-Za-z]', "_", "%s-%s" % (label, data["sha"][:8]))
        blocks.append("static const unsigned char %s_anchor[] = { %s };"
                      % (ident, ", ".join(data["sig_anchor"])))
        for entry_name, _off, sig in data["entries"]:
            blocks.append("static const unsigned char %s_%s[] = { %s };"
                          % (ident, entry_name, ", ".join(sig)))
        fields = ['"%s"' % label, "0x%xULL" % data["anchor"], "%s_anchor" % ident]
        for entry_name, off, _sig in data["entries"]:
            fields += ["0x%xULL" % off, "%s_%s" % (ident, entry_name)]
        entries.append("    { %s }," % ", ".join(fields))

    text = HEADER
    text += "/* driver builds the kext can fall back to */\n" + "\n".join(blocks) + "\n\n"
    text += "static const NvrmLegacyBinding kLegacyBindings[] = {\n" + "\n".join(entries) + "\n};\n"
    text += "\nstatic const int kLegacyBindingCount = sizeof(kLegacyBindings) / sizeof(kLegacyBindings[0]);\n"
    open(dst, "w").write(text)
    print("legacy tables: %d" % len(entries))


def main():
    if len(sys.argv) < 4:
        print(__doc__)
        return 2
    if sys.argv[1] == "--archive":
        archive(sys.argv[2], sys.argv[3], sys.argv[4] if len(sys.argv) > 4 else "current")
        return 0
    if sys.argv[1] == "--generate":
        generate(sys.argv[2], sys.argv[3])
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
