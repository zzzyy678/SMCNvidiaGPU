/* nvrt_check.cpp — run the kext's runtime resolver (kext/nvrm_runtime.h) in user space against an NVRM
 * binary and compare what it decodes with what nvrm_bindings.py lifts from the same binary.
 *
 * The two get there independently: the script disassembles with objdump and pattern-matches the mnemonics,
 * the resolver reads the symbol table and matches raw bytes. If they agree on every offset, signature and
 * OBJGPU field for a driver, the kernel would bind that driver with the same layout a rebuild would give.
 *
 * It also checks the in-memory guard the kext applies before binding: in a copy of the image, each decoded
 * instruction's displacement is changed in turn, and the copy must be refused.
 *
 * Build and run through tools/test/run.sh, which generates the reference header first.
 */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <mach-o/loader.h>
#include <mach-o/nlist.h>

typedef uint32_t UInt32;
typedef uint64_t UInt64;

#include "nvrm_runtime.h"
#include "nvrm_bindings.h"   /* reference, generated by run.sh from the same binary */

static unsigned char *gImg;
static size_t gImgLen;

static bool readImg(void *, UInt64 off, void *buf, size_t len)
{
    if (off > gImgLen || len > gImgLen - off)
        return false;
    memcpy(buf, gImg + off, len);
    return true;
}
static void *allocMem(size_t n) { return malloc(n); }
static void freeMem(void *p, size_t) { free(p); }

/* The checks nvrm_runtime_install() makes in the kernel, against a buffer standing in for loaded code. */
static const char *loadedMatches(const unsigned char *mem, const NvrmRuntime &rt)
{
    for (unsigned k = 0; k < NVRT_COUNT; k++)
        if (memcmp(mem + rt.off[k], rt.sig[k], NVRM_RT_SIG_LEN) != 0)
            return "entry signature";
    for (unsigned k = 0; k < NVRT_SITES; k++) {
        const NvrtSite &s = rt.site[k];
        if (!s.len || memcmp(mem + s.off, s.bytes, s.len) != 0)
            return "field instruction";
    }
    return nullptr;
}

static int gFailures;

static void cmpOff(const char *what, UInt64 got, UInt64 want)
{
    bool ok = got == want;
    printf("  %-22s %#10llx  %#10llx  %s\n", what, (unsigned long long)got, (unsigned long long)want,
           ok ? "ok" : "DIFFERENT");
    if (!ok)
        gFailures++;
}

static void cmpSig(const char *what, const unsigned char *got, const unsigned char *want)
{
    bool ok = memcmp(got, want, NVRM_RT_SIG_LEN) == 0;
    printf("  %-22s %s\n", what, ok ? "same 16 bytes" : "DIFFERENT");
    if (!ok)
        gFailures++;
}

int main(int argc, char **argv)
{
    if (argc != 2) {
        fprintf(stderr, "usage: %s /path/to/NVRM\n", argv[0]);
        return 2;
    }
    FILE *f = fopen(argv[1], "rb");
    if (!f) {
        perror(argv[1]);
        return 2;
    }
    fseek(f, 0, SEEK_END);
    gImgLen = (size_t)ftell(f);
    rewind(f);
    gImg = (unsigned char *)malloc(gImgLen);
    if (!gImg || fread(gImg, 1, gImgLen, f) != gImgLen) {
        fprintf(stderr, "cannot read %s\n", argv[1]);
        return 2;
    }
    fclose(f);

    NvrmRuntime rt;
    if (!nvrm_runtime_resolve(readImg, nullptr, allocMem, freeMem, &rt)) {
        printf("resolver refused this driver: %s\n", rt.why);
        return 1;
    }

    printf("%s\n", argv[1]);
    printf("  %-22s %10s  %10s\n", "", "resolver", "bindings.py");
    cmpOff("anchor", rt.off[NVRT_ANCHOR], NVRM_ANCHOR_OFF);
    cmpOff("gpumgrGetGpu", rt.off[NVRT_GPU], NVRM_OFF_gpumgrGetGpu);
    cmpOff("createRusd", rt.off[NVRT_CREATE], NVRM_OFF_createRusd);
    cmpOff("linkRusd", rt.off[NVRT_LINK], NVRM_OFF_linkRusd);
    cmpOff("lock", rt.off[NVRT_LOCK], NVRM_OFF_lock);
    cmpOff("unlock", rt.off[NVRT_UNLOCK], NVRM_OFF_unlock);
    cmpOff("pmEnter", rt.off[NVRT_PMIN], NVRM_OFF_pmEnter);
    cmpOff("pmExit", rt.off[NVRT_PMOUT], NVRM_OFF_pmExit);
    cmpOff("hInternalClient", rt.hClient, OFF_HINTERNAL_CLIENT);
    cmpOff("hInternalSubdevice", rt.hSubdevice, OFF_HINTERNAL_SUBDEVICE);
    cmpOff("physicalRmApi", rt.physicalRmApi, OFF_PHYSICAL_RMAPI);
    cmpOff("RM_API::Control", rt.rmapiControl, OFF_RMAPI_CONTROL);
    cmpOff("usd.pMemDesc", rt.usdMemDesc, OFF_USD_PMEMDESC);
    cmpOff("usd.pMapBuffer", rt.usdMapBuffer, OFF_USD_PMAPBUFFER);
    cmpOff("usd.data", rt.usdData, OFF_USD_DATA);
    cmpSig("sig anchor", rt.sig[NVRT_ANCHOR], NVRM_SIG_anchor);
    cmpSig("sig gpumgrGetGpu", rt.sig[NVRT_GPU], NVRM_SIG_gpumgrGetGpu);
    cmpSig("sig createRusd", rt.sig[NVRT_CREATE], NVRM_SIG_createRusd);
    cmpSig("sig linkRusd", rt.sig[NVRT_LINK], NVRM_SIG_linkRusd);
    cmpSig("sig lock", rt.sig[NVRT_LOCK], NVRM_SIG_lock);
    cmpSig("sig unlock", rt.sig[NVRT_UNLOCK], NVRM_SIG_unlock);
    cmpSig("sig pmEnter", rt.sig[NVRT_PMIN], NVRM_SIG_pmEnter);
    cmpSig("sig pmExit", rt.sig[NVRT_PMOUT], NVRM_SIG_pmExit);

    /* The guard: an identical image binds, and any changed field displacement is refused. */
    unsigned char *mem = (unsigned char *)malloc(gImgLen);
    memcpy(mem, gImg, gImgLen);
    const char *why = loadedMatches(mem, rt);
    printf("  %-22s %s\n", "identical image", why ? "REFUSED" : "accepted");
    if (why)
        gFailures++;
    for (unsigned k = 0; k < NVRT_SITES; k++) {
        const NvrtSite &s = rt.site[k];
        memcpy(mem, gImg, gImgLen);
        mem[s.off + s.len - 4] ^= 0x08;   /* move the field by 8 bytes, as a layout change would */
        why = loadedMatches(mem, rt);
        char label[32];
        snprintf(label, sizeof label, "field moved @%#llx", (unsigned long long)s.off);
        printf("  %-22s %s\n", label, why ? "refused" : "ACCEPTED");
        if (!why)
            gFailures++;
    }
    free(mem);
    free(gImg);

    printf(gFailures ? "FAIL: %d difference(s)\n" : "PASS\n", gFailures);
    return gFailures ? 1 : 0;
}
